// Runs the rules engine on the answer key's expected extraction and checks
// that each sample lands in the right verdict band with the right flags.

import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { analyze, monthlyPayment, normalizeDeal } from "../rules.js";
import { TYPICAL_APR } from "../data/lookups.js";

const answerKey = JSON.parse(
  readFileSync(new URL("../../sample-contracts/answer_key.json", import.meta.url), "utf8"),
);

// answer_key.json stores taxes as an object; the schema uses a line-item array.
const toDeal = (expected) => ({
  ...expected,
  taxes_and_government_fees: Object.entries(expected.taxes_and_government_fees ?? {}).map(
    ([name, amount]) => ({ name, amount }),
  ),
});

const run = (file) => {
  const c = answerKey.find((s) => s.file === file);
  return analyze(toDeal(c.expected_extraction), {
    creditTier: c.test_inputs.credit_tier,
    kbbValue: c.test_inputs.kbb_value_to_enter,
  });
};
const ids = (result) => result.flags.map((f) => f.id).sort();

test("01 clean: no flags, Fair deal", () => {
  const r = run("01_clean.pdf");
  assert.deepEqual(r.flags, []);
  assert.equal(r.score, 100);
  assert.equal(r.verdict.key, "fair");
});

test("02 predatory: every flag, Walk away", () => {
  const r = run("02_predatory.pdf");
  assert.deepEqual(ids(r), [
    "apr",
    "dealer_prep",
    "doc_fee",
    "gap",
    "nitrogen",
    "paint_protection",
    "price",
    "service_contract",
    "term",
    "vin_etch",
  ]);
  assert.equal(r.verdict.key, "walk");
  assert.ok(r.total_savings > 10000, `savings ${r.total_savings}`);
  const sc = r.flags.find((f) => f.id === "service_contract");
  assert.equal(sc.severity, "caution");
  assert.equal(sc.points, 0);
  assert.match(sc.title, /in interest/);
});

test("savings don't count the rate and term overlap twice", () => {
  // 02 has both a high APR and an 84-month term.
  const r = run("02_predatory.pdf");
  const red = r.flags.filter((f) => f.severity === "red");
  const lines = red.reduce((s, f) => s + f.dollar_impact, 0);
  assert.ok(r.savings_overlap > 0);
  assert.equal(r.total_savings, lines - r.savings_overlap);

  // Fixing both together: same principal changes, fair rate and 60 months at once.
  const { deal } = r;
  const total = (apr, months) => monthlyPayment(deal.amount_financed, apr, months) * months;
  const principal = red.filter((f) => f.id !== "apr" && f.id !== "term").reduce((s, f) => s + f.dollar_impact, 0);
  const together = principal + deal.total_of_payments - total(TYPICAL_APR.Good.apr, 60);
  assert.ok(Math.abs(r.total_savings - together) <= 3, `${r.total_savings} vs ${together}`);

  // With only one of the two flags there is nothing to subtract.
  assert.equal(run("03_borderline.pdf").savings_overlap, 0);
});

test("03 borderline: Negotiate", () => {
  const r = run("03_borderline.pdf");
  assert.deepEqual(ids(r), ["apr", "gap", "price", "term", "vin_etch"]);
  assert.equal(r.flags.find((f) => f.id === "term").severity, "caution");
  assert.equal(r.verdict.key, "negotiate", `score ${r.score}`);
});

test("04 buy-here-pay-here: flags and Walk away", () => {
  const r = run("04_risc_buy_here_pay_here.pdf");
  assert.deepEqual(ids(r), ["apr", "doc_fee", "gap", "gps", "price", "service_contract", "term"]);
  assert.match(r.flags.find((f) => f.id === "term").title, /high-mileage/);
  assert.equal(r.verdict.key, "walk");
});

// Contracts 05-10 (generated by tools/make_samples.py): verdict and flags.
const EXPECTED = {
  "05_negative_equity_trade.pdf": ["negotiate", ["apr", "gap", "price", "term", "tire_wheel"]],
  "06_new_car_promo_rate.pdf": ["fair", []],
  "07_risc_high_mileage.pdf": ["walk", ["apr", "doc_fee", "gps", "key_replacement", "price", "service_contract", "tire_wheel"]],
  "08_cash_deal_no_financing.pdf": ["negotiate", ["nitrogen", "paint_protection", "price"]],
  "09_payment_packing_84mo.pdf": ["walk", ["apr", "dealer_prep", "doc_fee", "key_replacement", "price", "service_contract", "term", "tire_wheel"]],
  "10_close_call.pdf": ["negotiate", ["apr", "gap", "price", "vin_etch"]],
};
for (const [file, [verdict, flagIds]] of Object.entries(EXPECTED)) {
  test(`${file.slice(0, 2)}: ${verdict} with expected flags`, () => {
    const r = run(file);
    assert.equal(r.verdict.key, verdict, `score ${r.score}`);
    assert.deepEqual(ids(r), flagIds);
  });
}

test("cash deal with no loan terms skips APR and term checks", () => {
  const r = run("08_cash_deal_no_financing.pdf");
  assert.equal(r.deal.apr, 0);
  assert.ok(!r.flags.some((f) => f.id === "apr" || f.id === "term"));
});

test("'Vehicle Service Agreement' is treated as a service contract", () => {
  const r = run("07_risc_high_mileage.pdf");
  assert.equal(r.flags.find((f) => f.id === "service_contract").severity, "caution");
});

test("points are capped at 25 per flag and score floors at 0", () => {
  for (const s of answerKey) {
    const r = run(s.file);
    assert.ok(r.score >= 0 && r.score <= 100);
    for (const f of r.flags) assert.ok(f.points <= 25);
  }
});

test("every flag carries a marked-up line item", () => {
  for (const s of answerKey) {
    for (const f of run(s.file).flags) {
      assert.ok(f.line?.label && f.line.charged && f.line.note, `${s.file} ${f.id}`);
    }
  }
});

test("loan math matches the contract", () => {
  const e = answerKey.find((s) => s.file === "01_clean.pdf").expected_extraction;
  assert.ok(Math.abs(monthlyPayment(e.amount_financed, e.apr, e.term_months) - e.monthly_payment) < 1);
});

test("normalizeDeal coerces strings and derives missing totals", () => {
  const d = normalizeDeal({
    vehicle_price: "$20,000",
    apr: "5%",
    term_months: "60",
    down_payment: 2000,
    fees: [{ name: "Doc fee", amount: "500" }],
  });
  assert.equal(d.amount_financed, 18500);
  assert.ok(d.monthly_payment > 340 && d.monthly_payment < 360);
  assert.equal(d.total_of_payments, Math.round(d.monthly_payment * 60 * 100) / 100);
});

test("Spanish: same verdicts and numbers, translated text", () => {
  for (const s of answerKey) {
    const en = run(s.file);
    const es = analyze(toDeal(s.expected_extraction), {
      creditTier: s.test_inputs.credit_tier,
      kbbValue: s.test_inputs.kbb_value_to_enter,
      lang: "es",
    });
    assert.equal(es.score, en.score);
    assert.equal(es.verdict.key, en.verdict.key);
    assert.deepEqual(es.flags.map((f) => f.dollar_impact), en.flags.map((f) => f.dollar_impact));
    assert.notEqual(es.counteroffer, en.counteroffer);
    assert.match(es.disclaimer, /No es asesoría financiera/);
  }
});

test("unknown lang falls back to English", () => {
  const c = answerKey[1];
  const r = analyze(toDeal(c.expected_extraction), { creditTier: "Good", kbbValue: 19800, lang: "fr" });
  assert.equal(r.verdict.label, "Walk away or get outside financing");
});

test("rejects an unknown credit tier", () => {
  assert.throws(() => analyze({}, { creditTier: "Great" }), /credit_tier/);
});

test("counteroffer lists one ask per flag", () => {
  const r = run("02_predatory.pdf");
  const bullets = r.counteroffer.split("\n").filter((l) => l.startsWith("- "));
  assert.equal(bullets.length, r.flags.length);
});
