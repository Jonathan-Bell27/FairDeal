// A deal whose printed totals reconcile, so any math flag comes from what the
// test changes: `pad` adds to the printed payment, `extra` to the amount financed.
const synthetic = ({ pad = 0, extra = 0, ...overrides } = {}) => {
  const d = {
    vehicle: "2022 Honda Civic",
    vehicle_price: 25000,
    apr: 9.9,
    term_months: 60,
    down_payment: 3000,
    trade_in_allowance: 0,
    trade_in_payoff: 0,
    fees: [{ name: "Documentary Service Fee", amount: 599 }],
    add_ons: [],
    taxes_and_government_fees: [{ name: "tavt", amount: 1750 }],
    ...overrides,
  };
  const financed = normalizeDeal(d).amount_financed + extra;
  const payment = Math.round(monthlyPayment(financed, d.apr, d.term_months) * 100) / 100 + pad;
  return { ...d, amount_financed: financed, monthly_payment: payment, total_of_payments: Math.round(payment * d.term_months * 100) / 100 };
};

test("contract math: a payment padded $45/mo is flagged once, with its implied APR", () => {
  // 84 months at 9.9% with Good credit, so the APR and term flags fire too.
  const clean = analyze(synthetic({ term_months: 84 }), { creditTier: "Good" });
  const padded = analyze(synthetic({ term_months: 84, pad: 45 }), { creditTier: "Good" });
  assert.deepEqual(ids(clean), ["apr", "term"]);
  assert.deepEqual(ids(padded), ["apr", "payment_gap", "term"]);

  const gap = padded.flags.find((f) => f.id === "payment_gap");
  assert.equal(gap.severity, "red");
  assert.equal(gap.dollar_impact, 45 * 84);
  assert.equal(gap.line.label, "Monthly payment");
  assert.match(gap.ask, /extra \$45 a month/);
  assert.match(gap.detail, /Edit the numbers/);
  const implied = Number(gap.detail.match(/about what a ([\d.]+)% APR would cost, not the 9\.9%/)[1]);
  assert.ok(implied > 9.9);
  const { amount_financed, monthly_payment } = padded.deal;
  assert.ok(Math.abs(monthlyPayment(amount_financed, implied, 84) - monthly_payment) < 1);

  // The term flag uses the loan math's payment, so the $45 isn't counted again
  // (within $1: the clean deal's printed payment is rounded to the cent).
  const term = (r) => r.flags.find((f) => f.id === "term");
  assert.equal(term(padded).severity, "red");
  assert.ok(Math.abs(term(padded).dollar_impact - term(clean).dollar_impact) <= 1);
  assert.ok(Math.abs(padded.total_savings - clean.total_savings - gap.dollar_impact) <= 1);
});

test("contract math: $1,500 financed but not on any line is flagged", () => {
  const r = analyze(synthetic({ extra: 1500 }), { creditTier: "Fair" });
  assert.deepEqual(ids(r), ["unexplained_amount"]);
  const f = r.flags[0];
  assert.equal(f.severity, "red");
  assert.equal(f.dollar_impact, 1500);
  assert.equal(r.total_savings, 1500);
  assert.match(f.title, /^\$1,500 in the loan isn't on any line/);
  assert.match(f.ask, /^Itemize or remove the \$1,500/);
  assert.match(f.detail, /Edit the numbers/);
  assert.equal(f.line.label, "Amount financed");
  assert.equal(f.line.charged, "$" + Math.round(r.deal.amount_financed).toLocaleString("en-US"));

  // Financing less than the lines add up to (a rebate) isn't flagged.
  assert.deepEqual(analyze(synthetic({ extra: -1000 }), { creditTier: "Fair" }).flags, []);
});

test("contract math: rounding never flags", () => {
  assert.deepEqual(analyze(synthetic({ pad: 1, extra: 20 }), { creditTier: "Fair" }).flags, []);
});

test("contract math: only numbers printed on the document are checked", () => {
  // No amount financed printed: normalizeDeal derives it, so nothing to audit.
  const noFinanced = analyze({ ...synthetic({ pad: 45 }), amount_financed: 0 }, { creditTier: "Fair" });
  assert.deepEqual(noFinanced.flags, []);

  // No payment printed: the derived payment isn't checked.
  const noPayment = analyze({ ...synthetic({ extra: 1500 }), monthly_payment: 0, total_of_payments: 0 }, { creditTier: "Fair" });
  assert.deepEqual(ids(noPayment), ["unexplained_amount"]);
});

test("negative equity: shown with its interest, not scored, no ask", () => {
  const deal = synthetic({ trade_in_allowance: 4000, trade_in_payoff: 7800 });
  const r = analyze(deal, { creditTier: "Fair", kbbValue: 25000 });
  assert.deepEqual(ids(r), ["negative_equity"]);
  const f = r.flags[0];
  assert.equal(f.severity, "caution");
  assert.equal(f.points, 0);
  assert.equal(f.ask, undefined);
  assert.equal(r.score, 100);
  assert.equal(r.total_savings, 0);
  assert.equal(f.dollar_impact, Math.round(monthlyPayment(3800, 9.9, 60) * 60 - 3800));
  assert.match(f.title, /^\$3,800 you still owe on your trade-in is rolled into this loan/);
  assert.match(f.detail, /\$7,800 on your trade-in .* \$4,000 for it/);
  assert.match(f.detail, /owe \$28,149 on a car worth about \$25,000 \(113% of its value\), so you'd owe more than the car is worth/);
  assert.deepEqual(f.line, { label: "Trade-in balance", charged: "$3,800", note: `old loan, +$${f.dollar_impact.toLocaleString("en-US")} interest`, strike: false });

  // Without a KBB value there's no loan-to-value sentence.
  const noKbb = analyze(deal, { creditTier: "Fair" }).flags[0];
  assert.equal(noKbb.dollar_impact, f.dollar_impact);
  assert.doesNotMatch(noKbb.detail, /worth/);

  // $50 or less is rounding.
  const small = synthetic({ trade_in_allowance: 4000, trade_in_payoff: 4040 });
  assert.deepEqual(analyze(small, { creditTier: "Fair" }).flags, []);
});

test("Spanish: contract math and negative equity", () => {
  const deal = synthetic({ term_months: 84, pad: 45, extra: 1500, trade_in_allowance: 4000, trade_in_payoff: 7800 });
  const opts = { creditTier: "Good", kbbValue: 25000 };
  const en = analyze(deal, opts);
  const es = analyze(deal, { ...opts, lang: "es" });
  assert.deepEqual(ids(en), ["apr", "negative_equity", "payment_gap", "term", "unexplained_amount"]);
  assert.deepEqual(es.flags.map((f) => f.dollar_impact), en.flags.map((f) => f.dollar_impact));
  const by = (id) => es.flags.find((f) => f.id === id);
  assert.equal(by("payment_gap").line.label, "Pago mensual");
  assert.match(by("payment_gap").detail, /tasa \(APR\) de alrededor de [\d.]+%, no el 9\.9% del contrato/);
  assert.match(by("payment_gap").detail, /Editar los números/);
  assert.equal(by("unexplained_amount").line.label, "Monto financiado");
  assert.match(by("unexplained_amount").title, /^Hay \$1,500 en el préstamo/);
  assert.equal(by("negative_equity").line.label, "Saldo del auto anterior");
  assert.match(by("negative_equity").detail, /de su valor\), así que desde el primer día deberías más/);
  for (const id of ["payment_gap", "unexplained_amount", "negative_equity"]) {
    const e = en.flags.find((f) => f.id === id);
    for (const k of ["title", "detail", "source", "category"]) assert.notEqual(by(id)[k], e[k], `${id} ${k}`);
    assert.notEqual(by(id).line.note, e.line.note, id);
  }
});
